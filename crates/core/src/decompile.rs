//! Turns a compiled model back into a QC and SMDs.

use std::collections::{HashMap, HashSet};
use std::fmt::Write;
use std::path::{Path, PathBuf};

use crate::inspect::{ModelSource, VTX_EXTENSIONS, read_companion, read_model};
use crate::vfs::Vfs;

use crate::mdl::phy::Phy;
use crate::mdl::vtx::Vtx;
use crate::mdl::vvd::{Vertex, Vvd};
use crate::mdl::{self, Bone, Model};
use crate::vdf::{self, Node, ParseOptions};

const FLAG_AUTOGENERATED_HITBOX: u32 = 0x1;
const FLAG_FORCE_OPAQUE: u32 = 0x4;
const FLAG_TRANSLUCENT_TWOPASS: u32 = 0x8;
const FLAG_HAS_SHADOW_LOD: u32 = 0x40;
const FLAG_USE_SHADOW_LOD_MATERIALS: u32 = 0x100;
const FLAG_NO_FORCED_FADE: u32 = 0x800;
const FLAG_FORCE_PHONEME_CROSSFADE: u32 = 0x1000;
const FLAG_CONSTANT_DIRECTIONAL_LIGHT_DOT: u32 = 0x2000;
const FLAG_AMBIENT_BOOST: u32 = 0x10000;
const FLAG_DO_NOT_CAST_SHADOWS: u32 = 0x20000;
const FLAG_CAST_TEXTURE_SHADOWS: u32 = 0x40000;

const CONTENTS_SOLID: i32 = 0x1;
const CONTENTS: [(i32, &str); 4] = [
	(0x1, "solid"),
	(0x8, "grate"),
	(0x2000000, "monster"),
	(0x10000000, "ladder"),
];

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct File {
	/// Relative to the output folder, forward slashes.
	pub path: String,
	pub text: String,
}

/// `vfs` is only needed for a game path.
pub fn run(
	vfs: Option<&Vfs>,
	source: &ModelSource,
	output_dir: &Path,
) -> Result<Vec<PathBuf>, String> {
	let (file, data) = read_model(vfs, source)?;
	let model = mdl::parse(&data).map_err(|e| e.to_string())?;
	let companion = |extensions: &[&str]| {
		extensions
			.iter()
			.find_map(|ext| read_companion(vfs, source, ext))
			.ok_or_else(|| format!("no .{} next to the model", extensions[0]))
			.and_then(|(_, data)| data)
	};
	let (vvd, vtx) = if model.has_geometry() {
		let vvd = mdl::vvd::parse(&companion(&["vvd"])?).map_err(|e| format!(".vvd: {e}"))?;
		let vtx =
			mdl::vtx::parse(&companion(&VTX_EXTENSIONS)?).map_err(|e| format!(".vtx: {e}"))?;
		(Some(vvd), Some(vtx))
	} else {
		(None, None)
	};
	let stem = Path::new(&file.path)
		.file_stem()
		.map(|s| smd_name(&s.to_string_lossy(), "model"))
		.unwrap_or_else(|| "model".into());
	// Collision is optional; a .phy that can't be read is left out like a missing one.
	let phy = read_companion(vfs, source, "phy")
		.and_then(|(_, data)| data.ok())
		.and_then(|data| mdl::phy::parse(&data).ok());
	let ani = read_companion(vfs, source, "ani").and_then(|(_, data)| data.ok());
	let input = Input {
		mdl: &data,
		ani: ani.as_deref(),
		vvd: vvd.as_ref(),
		vtx: vtx.as_ref(),
		phy: phy.as_ref(),
	};
	let files = decompile(&model, &input, &stem)?;
	let mut written = Vec::with_capacity(files.len());
	for f in files {
		let path = output_dir.join(&f.path);
		if let Some(parent) = path.parent() {
			std::fs::create_dir_all(parent).map_err(|e| format!("{}: {e}", parent.display()))?;
		}
		std::fs::write(&path, f.text).map_err(|e| format!("{}: {e}", path.display()))?;
		written.push(path);
	}
	Ok(written)
}

/// The model's files; the .vvd and .vtx are only needed with geometry.
pub struct Input<'a> {
	pub mdl: &'a [u8],
	pub ani: Option<&'a [u8]>,
	pub vvd: Option<&'a Vvd>,
	pub vtx: Option<&'a Vtx>,
	pub phy: Option<&'a Phy>,
}

pub fn decompile(model: &Model, input: &Input, stem: &str) -> Result<Vec<File>, String> {
	let mut files = Vec::new();
	let mut used = HashSet::new();
	let mut body_parts = Vec::new();
	let mut lods = String::new();
	let mut flex_blocks = HashMap::new();
	if model.has_geometry() {
		let (Some(vvd), Some(vtx)) = (input.vvd, input.vtx) else {
			return Err("the model needs its .vvd and .vtx".into());
		};
		if vvd.checksum != model.checksum || vtx.checksum != model.checksum {
			return Err("the .vvd or .vtx belongs to another build of the model".into());
		}
		let mut out = Output {
			used: &mut used,
			body_parts: &mut body_parts,
			files: &mut files,
		};
		lods = geometry(model, vvd, vtx, stem, &mut out)?;
		let flexes = mdl::flex::parse(input.mdl).map_err(|e| format!("flexes: {e}"))?;
		flex_blocks = flex::blocks(model, &flexes, vvd, &body_parts, &mut files);
	}
	let anims = mdl::anim::parse(input.mdl, model.version).map_err(|e| e.to_string())?;
	let animation = if anims.descs.is_empty() {
		let idle = format!("{stem}_anims/idle.smd");
		files.push(File {
			path: idle.clone(),
			text: idle_smd(model),
		});
		let name = model.sequences.first().map_or("idle", |s| s.name.as_str());
		format!("$sequence {} {}\n", quote(name), quote(&idle))
	} else {
		animation::animations(
			model, &anims, input.mdl, input.ani, stem, &mut used, &mut files,
		)?
	};
	let collision = match input.phy {
		Some(phy) if phy.checksum != model.checksum => {
			"// The .phy belongs to another build of the model; collision is left out.\n".into()
		}
		Some(phy) if !phy.solids.is_empty() => {
			let (smd, block) = physics::physics(model, phy, stem);
			files.push(smd);
			block
		}
		_ => String::new(),
	};
	let (vrd, procedural) = procedural::procedural_bones(model, stem);
	files.extend(vrd);
	files.push(File {
		path: format!("{stem}.qc"),
		text: qc(
			model,
			&body_parts,
			&flex_blocks,
			&lods,
			&procedural,
			&animation,
			&collision,
		),
	});
	Ok(files)
}

struct Output<'a> {
	used: &'a mut HashSet<String>,
	body_parts: &'a mut Vec<(String, Vec<Option<String>>)>,
	files: &'a mut Vec<File>,
}

/// Reference and LOD SMDs; returns the `$lod` blocks.
fn geometry(
	model: &Model,
	vvd: &Vvd,
	vtx: &Vtx,
	stem: &str,
	out: &mut Output,
) -> Result<String, String> {
	let Output {
		used,
		body_parts,
		files,
	} = out;
	// Each submodel with an SMD: its name, the .mdl submodel and the .vtx LODs.
	let mut written: Vec<(String, &mdl::SubModel, &[mdl::vtx::Lod])> = Vec::new();
	for (p, part) in model.body_parts.iter().enumerate() {
		let mut choices = Vec::new();
		for (m, sub) in part.models.iter().enumerate() {
			let meshes = vtx
				.body_parts
				.get(p)
				.and_then(|models| models.get(m))
				.and_then(|vtx| vtx.lods.first())
				.map(|lod| lod.meshes.as_slice())
				.unwrap_or_default();
			if sub.name.is_empty() || meshes.iter().all(|mesh| mesh.triangles.is_empty()) {
				choices.push(None);
				continue;
			}
			let name = unique(used, &smd_name(&sub.name, stem));
			let text = reference_smd(model, vvd, sub, meshes)?;
			files.push(File {
				path: name.clone(),
				text,
			});
			let lods = vtx.body_parts[p][m].lods.as_slice();
			written.push((name.clone(), sub, lods));
			choices.push(Some(name));
		}
		body_parts.push((part.name.clone(), choices));
	}
	lods(model, vvd, vtx, &written, used, files)
}

/// `$lod` and `$shadowlod`, with an SMD for each submodel that differs from LOD 0.
fn lods(
	model: &Model,
	vvd: &Vvd,
	vtx: &Vtx,
	written: &[(String, &mdl::SubModel, &[mdl::vtx::Lod])],
	used: &mut HashSet<String>,
	files: &mut Vec<File>,
) -> Result<String, String> {
	let count = written
		.iter()
		.map(|(_, _, lods)| lods.len())
		.max()
		.unwrap_or(0);
	let shadow = model.flags & FLAG_HAS_SHADOW_LOD != 0 && count > 1;
	let mut q = String::new();
	for lod in 1..count {
		let is_shadow = shadow && lod == count - 1;
		let mut lines = String::new();
		for (name, sub, lods) in written {
			let Some(meshes) = lods.get(lod).map(|l| l.meshes.as_slice()) else {
				continue;
			};
			if meshes.iter().all(|m| m.triangles.is_empty()) {
				let _ = writeln!(lines, "\tremovemodel {}", quote(name));
				continue;
			}
			if lods.first().is_some_and(|first| first.meshes == meshes) {
				continue;
			}
			let suffix = if is_shadow {
				"shadowlod".to_owned()
			} else {
				format!("lod{lod}")
			};
			let lod_name = unique(used, &format!("{}_{suffix}", name.trim_end_matches(".smd")));
			files.push(File {
				path: lod_name.clone(),
				text: reference_smd(model, vvd, sub, meshes)?,
			});
			let _ = writeln!(lines, "\treplacemodel {} {}", quote(name), quote(&lod_name));
		}
		for (from, to) in replaced_bones(vvd, written, lod) {
			let name = |b: usize| model.bones.get(b).map_or("", |b| b.name.as_str());
			let _ = writeln!(
				lines,
				"\treplacebone {} {}",
				quote(name(from)),
				quote(name(to))
			);
		}
		for (material, replacement) in vtx.material_replacements.get(lod).into_iter().flatten() {
			if let Some(original) = model.materials.get(*material as usize) {
				let _ = writeln!(
					lines,
					"\treplacematerial {} {}",
					quote(original),
					quote(replacement)
				);
			}
		}
		if is_shadow {
			if model.flags & FLAG_USE_SHADOW_LOD_MATERIALS != 0 {
				lines.push_str("\tuse_shadowlod_materials\n");
			}
			let _ = writeln!(q, "$shadowlod\n{{\n{lines}}}");
		} else {
			let switch = written
				.iter()
				.find_map(|(_, _, lods)| lods.get(lod))
				.map_or(0.0, |l| l.switch_point);
			let _ = writeln!(q, "$lod {}\n{{\n{lines}}}", num(switch));
		}
	}
	Ok(q)
}

/// studiomdl weights LOD vertices like the nearest LOD 0 one, so dropped bones become `replacebone`.
fn replaced_bones(
	vvd: &Vvd,
	written: &[(String, &mdl::SubModel, &[mdl::vtx::Lod])],
	lod: usize,
) -> Vec<(usize, usize)> {
	let weights = |v: &Vertex| -> HashMap<usize, f32> {
		let mut w = HashMap::new();
		for i in 0..(v.bone_count as usize).clamp(1, 3) {
			*w.entry(v.bones[i] as usize).or_default() += v.weights[i];
		}
		w
	};
	let vertices = |sub: &mdl::SubModel, l: &mdl::vtx::Lod| {
		let mut indices: Vec<usize> = sub
			.meshes
			.iter()
			.zip(&l.meshes)
			.flat_map(|(mesh, vtx_mesh)| {
				let first = sub.first_vertex as usize + mesh.first_vertex as usize;
				vtx_mesh
					.triangles
					.iter()
					.flatten()
					.map(move |&c| first + c as usize)
			})
			.collect();
		indices.sort_unstable();
		indices.dedup();
		indices
			.into_iter()
			.filter_map(|i| vvd.vertices.get(i))
			.collect::<Vec<_>>()
	};
	let mut votes: HashMap<(usize, usize), usize> = HashMap::new();
	let mut present: HashSet<usize> = HashSet::new();
	for (_, sub, lods) in written {
		let (Some(base), Some(this)) = (lods.first(), lods.get(lod)) else {
			continue;
		};
		let mut base = vertices(sub, base);
		base.sort_by(|a, b| a.position[0].total_cmp(&b.position[0]));
		for v in vertices(sub, this) {
			let after = weights(v);
			present.extend(after.keys());
			// studiomdl takes the weights of the nearest LOD 0 vertex.
			let Some(original) = nearest(&base, v.position) else {
				continue;
			};
			let before = weights(original);
			for &gone in before.keys().filter(|b| !after.contains_key(b)) {
				let gained = after
					.iter()
					.map(|(&b, &w)| (b, w - before.get(&b).copied().unwrap_or(0.0)))
					.max_by(|x, y| x.1.total_cmp(&y.1));
				if let Some((to, _)) = gained {
					*votes.entry((gone, to)).or_default() += 1;
				}
			}
		}
	}
	votes.retain(|(from, _), _| !present.contains(from));
	let mut best: HashMap<usize, (usize, usize)> = HashMap::new();
	for ((from, to), n) in votes {
		let entry = best.entry(from).or_insert((to, 0));
		if n > entry.1 || (n == entry.1 && to < entry.0) {
			*entry = (to, n);
		}
	}
	let mut out: Vec<(usize, usize)> = best.into_iter().map(|(from, (to, _))| (from, to)).collect();
	out.sort_unstable();
	out
}

/// `sorted` is ordered by X, so the search stops once X alone is too far.
fn nearest<'a>(sorted: &[&'a Vertex], p: [f32; 3]) -> Option<&'a Vertex> {
	let distance = |v: &Vertex| (0..3).map(|i| (v.position[i] - p[i]).powi(2)).sum::<f32>();
	let start = sorted.partition_point(|v| v.position[0] < p[0]);
	let mut best: Option<(&Vertex, f32)> = None;
	let mut check = |v: &'a Vertex| {
		let dx = (v.position[0] - p[0]).powi(2);
		if best.is_some_and(|(_, d)| dx > d) {
			return false;
		}
		let d = distance(v);
		if best.is_none_or(|(_, b)| d < b) {
			best = Some((v, d));
		}
		true
	};
	for v in &sorted[start..] {
		if !check(v) {
			break;
		}
	}
	for v in sorted[..start].iter().rev() {
		if !check(v) {
			break;
		}
	}
	best.map(|(v, _)| v)
}

fn smd_name(submodel: &str, stem: &str) -> String {
	let base = submodel.strip_suffix(".smd").unwrap_or(submodel);
	let clean: String = base
		.chars()
		.map(|c| {
			if c.is_ascii_alphanumeric() || "-_.".contains(c) {
				c
			} else {
				'_'
			}
		})
		.collect();
	if clean.is_empty() {
		stem.to_owned()
	} else {
		clean
	}
}

fn unique(used: &mut HashSet<String>, base: &str) -> String {
	let mut name = format!("{base}.smd");
	let mut n = 2;
	while !used.insert(name.to_lowercase()) {
		name = format!("{base}_{n}.smd");
		n += 1;
	}
	name
}

/// Six decimals, without a minus sign on zero; NaN and infinity become zero.
fn num(v: f32) -> String {
	let v = if v.is_finite() { v } else { 0.0 };
	let text = format!("{v:.6}");
	if text
		.trim_start_matches('-')
		.bytes()
		.all(|b| b == b'0' || b == b'.')
	{
		text.trim_start_matches('-').to_owned()
	} else {
		text
	}
}

fn vec3(v: [f32; 3]) -> String {
	format!("{} {} {}", num(v[0]), num(v[1]), num(v[2]))
}

fn quote(text: &str) -> String {
	format!("\"{}\"", text.replace('"', "'"))
}

fn nodes_and_skeleton(out: &mut String, bones: &[Bone], adjust_roots: bool) {
	out.push_str("version 1\nnodes\n");
	for (i, bone) in bones.iter().enumerate() {
		let _ = writeln!(out, "{i} {} {}", quote(&bone.name), bone.parent);
	}
	out.push_str("end\nskeleton\ntime 0\n");
	for (i, bone) in bones.iter().enumerate() {
		let (mut position, mut rotation) = (bone.position, bone.rotation);
		// studiomdl turns input 90° about Z; in animations that lands on the root bones.
		if adjust_roots && bone.parent < 0 {
			position = [position[1], -position[0], position[2]];
			rotation[2] -= std::f32::consts::FRAC_PI_2;
		}
		let _ = writeln!(out, "{i} {} {}", vec3(position), vec3(rotation));
	}
	out.push_str("end\n");
}

fn reference_smd(
	model: &Model,
	vvd: &Vvd,
	sub: &mdl::SubModel,
	meshes: &[mdl::vtx::Mesh],
) -> Result<String, String> {
	let mut out = String::new();
	nodes_and_skeleton(&mut out, &model.bones, false);
	out.push_str("triangles\n");
	let skin = model.skins.first();
	for (mdl_mesh, vtx_mesh) in sub.meshes.iter().zip(meshes) {
		let material = skin
			.and_then(|row| row.get(mdl_mesh.skin_slot as usize))
			.and_then(|&m| model.materials.get(m as usize))
			.map_or("default", String::as_str);
		let first = sub.first_vertex as usize + mdl_mesh.first_vertex as usize;
		for triangle in &vtx_mesh.triangles {
			let _ = writeln!(out, "{material}");
			// The .vtx winds triangles the other way round from an SMD.
			for corner in [triangle[0], triangle[2], triangle[1]] {
				let vertex = vvd
					.vertices
					.get(first + corner as usize)
					.ok_or("a triangle points past the .vvd vertices")?;
				vertex_line(&mut out, vertex, model.is_static_prop());
			}
		}
	}
	out.push_str("end\n");
	Ok(out)
}

fn vertex_line(out: &mut String, v: &Vertex, static_prop: bool) {
	// A static prop's vertices are stored turned 90° about Z; studiomdl will turn them again.
	let turn = |p: [f32; 3]| {
		if static_prop { [p[1], -p[0], p[2]] } else { p }
	};
	let links = (v.bone_count as usize).clamp(1, 3);
	let _ = write!(
		out,
		"{} {} {} {} {} {}",
		v.bones[0],
		vec3(turn(v.position)),
		vec3(turn(v.normal)),
		num(v.uv[0]),
		num(1.0 - v.uv[1]),
		links
	);
	for i in 0..links {
		let _ = write!(out, " {} {}", v.bones[i], num(v.weights[i]));
	}
	out.push('\n');
}

fn idle_smd(model: &Model) -> String {
	let mut out = String::new();
	nodes_and_skeleton(&mut out, &model.bones, true);
	out
}

fn qc(
	model: &Model,
	body_parts: &[(String, Vec<Option<String>>)],
	flex_blocks: &HashMap<usize, String>,
	lods: &str,
	procedural: &str,
	animation: &str,
	collision: &str,
) -> String {
	let mut q = String::new();
	let flags = model.flags;
	let _ = writeln!(q, "$modelname {}", quote(&model.name));
	if model.is_static_prop() {
		q.push_str("$staticprop\n");
	}
	q.push('\n');

	for (p, (name, choices)) in body_parts.iter().enumerate() {
		match choices.as_slice() {
			[Some(smd)] if flex_blocks.contains_key(&p) => {
				let _ = writeln!(
					q,
					"$model {} {} {{\n{}}}",
					quote(name),
					quote(smd),
					flex_blocks[&p]
				);
			}
			[Some(smd)] => {
				let _ = writeln!(q, "$body {} {}", quote(name), quote(smd));
			}
			_ => {
				let _ = writeln!(q, "$bodygroup {}\n{{", quote(name));
				for choice in choices {
					match choice {
						Some(smd) => {
							let _ = writeln!(q, "\tstudio {}", quote(smd));
						}
						None => q.push_str("\tblank\n"),
					}
				}
				q.push_str("}\n");
			}
		}
	}
	q.push('\n');
	if !lods.is_empty() {
		let _ = writeln!(q, "{lods}");
	}

	if !model.surface_prop.is_empty() {
		let _ = writeln!(q, "$surfaceprop {}", quote(&model.surface_prop));
	}
	if model.contents != CONTENTS_SOLID {
		let names: Vec<&str> = CONTENTS
			.iter()
			.filter(|(bit, _)| model.contents & bit != 0)
			.map(|(_, name)| *name)
			.collect();
		let names = if names.is_empty() {
			vec!["notsolid"]
		} else {
			names
		};
		let _ = writeln!(
			q,
			"$contents {}",
			names.iter().map(|n| quote(n)).collect::<Vec<_>>().join(" ")
		);
	}
	for (flag, command) in [
		(FLAG_FORCE_OPAQUE, "$opaque"),
		(FLAG_NO_FORCED_FADE, "$noforcedfade"),
		(FLAG_FORCE_PHONEME_CROSSFADE, "$forcephonemecrossfade"),
		(FLAG_AMBIENT_BOOST, "$ambientboost"),
		(FLAG_DO_NOT_CAST_SHADOWS, "$donotcastshadows"),
		(FLAG_CAST_TEXTURE_SHADOWS, "$casttextureshadows"),
	] {
		if flags & flag != 0 {
			let _ = writeln!(q, "{command}");
		}
	}
	if flags & FLAG_TRANSLUCENT_TWOPASS != 0 && flags & FLAG_FORCE_OPAQUE == 0 {
		q.push_str("$mostlyopaque\n");
	}
	if flags & FLAG_CONSTANT_DIRECTIONAL_LIGHT_DOT != 0 {
		let _ = writeln!(
			q,
			"$constantdirectionallight {}",
			num(model.directional_light_dot as f32 / 255.0)
		);
	}
	let turned = |p: [f32; 3]| [p[1], -p[0], p[2]];
	let _ = writeln!(q, "$illumposition {}", vec3(turned(model.illum_position)));
	if model.eye_position != [0.0; 3] {
		let _ = writeln!(q, "$eyeposition {}", vec3(turned(model.eye_position)));
	}
	q.push('\n');

	// Otherwise studiomdl drops bones no vertex uses, such as the hands a c_ model is bonemerged to.
	if !model.is_static_prop() {
		for bone in &model.bones {
			let parent = model
				.bones
				.get(bone.parent.max(0) as usize)
				.filter(|_| bone.parent >= 0)
				.map_or("", |p| p.name.as_str());
			let r = bone.rotation.map(f32::to_degrees);
			let _ = writeln!(
				q,
				"$definebone {} {} {} {} 0 0 0 0 0 0",
				quote(&bone.name),
				quote(parent),
				vec3(bone.position),
				vec3([r[1], r[2], r[0]])
			);
		}
		q.push('\n');
	}

	q.push_str(procedural);
	for bone in &model.bones {
		if let Some(j) = &bone.jiggle {
			jiggle_bone(&mut q, &bone.name, j);
		}
	}

	for folder in &model.material_folders {
		let _ = writeln!(q, "$cdmaterials {}", quote(folder));
	}
	texture_group(&mut q, model);
	q.push('\n');

	let bone_name = |i: i32| {
		model
			.bones
			.get(i as usize)
			.map_or(String::new(), |b| b.name.clone())
	};
	for attachment in &model.attachments {
		let m = attachment.matrix;
		let [pitch, yaw, roll] = matrix_angles(m);
		let _ = writeln!(
			q,
			"$attachment {} {} {} rotate {}",
			quote(&attachment.name),
			quote(&bone_name(attachment.bone)),
			vec3([m[0][3], m[1][3], m[2][3]]),
			vec3([pitch, yaw, roll])
		);
	}
	if !model.attachments.is_empty() {
		q.push('\n');
	}

	if flags & FLAG_AUTOGENERATED_HITBOX == 0 {
		for set in &model.hitbox_sets {
			let _ = writeln!(q, "$hboxset {}", quote(&set.name));
			for b in &set.boxes {
				let _ = write!(
					q,
					"$hbox {} {} {} {}",
					b.group,
					quote(&bone_name(b.bone)),
					vec3(b.min),
					vec3(b.max)
				);
				if !b.name.is_empty() {
					let _ = write!(q, " {}", quote(&b.name));
				}
				q.push('\n');
			}
		}
		if !model.hitbox_sets.is_empty() {
			q.push('\n');
		}
	}

	if let Some(text) = key_values(&model.key_values) {
		let _ = writeln!(q, "$keyvalues\n{{\n{text}}}\n");
	}
	for include in &model.include_models {
		// studiomdl puts models/ in front itself.
		let path = include.replace('\\', "/");
		let path = path
			.get(..7)
			.filter(|head| head.eq_ignore_ascii_case("models/"))
			.map_or(path.as_str(), |_| &path[7..]);
		let _ = writeln!(q, "$includemodel {}", quote(path));
	}

	let _ = writeln!(q, "$bbox {} {}", vec3(model.hull_min), vec3(model.hull_max));
	if model.view_min != [0.0; 3] || model.view_max != [0.0; 3] {
		let _ = writeln!(q, "$cbox {} {}", vec3(model.view_min), vec3(model.view_max));
	}
	q.push('\n');

	if !collision.is_empty() {
		let _ = writeln!(q, "{collision}");
	}

	q.push_str(animation);
	q
}

fn jiggle_bone(q: &mut String, bone: &str, j: &mdl::Jiggle) {
	let deg = |r: f32| num(r.to_degrees());
	let has = |flag: u32| j.flags & flag != 0;
	let _ = writeln!(q, "$jigglebone {}\n{{", quote(bone));
	for (flag, block) in [
		(mdl::JIGGLE_FLEXIBLE, "is_flexible"),
		(mdl::JIGGLE_RIGID, "is_rigid"),
	] {
		if !has(flag) {
			continue;
		}
		let _ = writeln!(
			q,
			"\t{block}\n\t{{\n\t\tlength {}\n\t\ttip_mass {}",
			num(j.length),
			num(j.tip_mass)
		);
		if flag == mdl::JIGGLE_FLEXIBLE {
			for (key, v) in [
				("yaw_stiffness", j.yaw_stiffness),
				("yaw_damping", j.yaw_damping),
				("pitch_stiffness", j.pitch_stiffness),
				("pitch_damping", j.pitch_damping),
				("along_stiffness", j.along_stiffness),
				("along_damping", j.along_damping),
			] {
				let _ = writeln!(q, "\t\t{key} {}", num(v));
			}
			if !has(mdl::JIGGLE_LENGTH_CONSTRAINT) {
				q.push_str("\t\tallow_length_flex\n");
			}
		}
		if has(mdl::JIGGLE_ANGLE_CONSTRAINT) {
			let _ = writeln!(q, "\t\tangle_constraint {}", deg(j.angle_limit));
		}
		for (constraint, name, range, friction, bounce) in [
			(
				mdl::JIGGLE_YAW_CONSTRAINT,
				"yaw",
				j.yaw,
				j.yaw_friction,
				j.yaw_bounce,
			),
			(
				mdl::JIGGLE_PITCH_CONSTRAINT,
				"pitch",
				j.pitch,
				j.pitch_friction,
				j.pitch_bounce,
			),
		] {
			if has(constraint) {
				let _ = writeln!(
					q,
					"\t\t{name}_constraint {} {}\n\t\t{name}_friction {}\n\t\t{name}_bounce {}",
					deg(range[0]),
					deg(range[1]),
					num(friction),
					num(bounce)
				);
			}
		}
		q.push_str("\t}\n");
	}
	if has(mdl::JIGGLE_BASE_SPRING) {
		let _ = writeln!(
			q,
			"\thas_base_spring\n\t{{\n\t\tbase_mass {}\n\t\tstiffness {}\n\t\tdamping {}",
			num(j.base_mass),
			num(j.base_stiffness),
			num(j.base_damping)
		);
		for (name, [min, max, friction]) in [
			("left", j.base_left),
			("up", j.base_up),
			("forward", j.base_forward),
		] {
			let _ = writeln!(
				q,
				"\t\t{name}_constraint {} {}\n\t\t{name}_friction {}",
				num(min),
				num(max),
				num(friction)
			);
		}
		q.push_str("\t}\n");
	}
	if has(mdl::JIGGLE_BOING) {
		let [speed, angle, damping, frequency, amplitude] = j.boing;
		// studiomdl keeps the cosine of the angle.
		let _ = writeln!(
			q,
			"\tis_boing\n\t{{\n\t\timpact_speed {}\n\t\timpact_angle {}\n\t\tdamping_rate {}\n\t\tfrequency {}\n\t\tamplitude {}\n\t}}",
			num(speed),
			num(angle.clamp(-1.0, 1.0).acos().to_degrees()),
			num(damping),
			num(frequency),
			num(amplitude)
		);
	}
	q.push_str("}\n");
}

/// Only the skin slots that differ between families, as studiomdl expects.
fn texture_group(q: &mut String, model: &Model) {
	let [first, rest @ ..] = model.skins.as_slice() else {
		return;
	};
	if rest.is_empty() {
		return;
	}
	let columns: Vec<usize> = (0..first.len())
		.filter(|&c| rest.iter().any(|row| row.get(c) != first.get(c)))
		.collect();
	if columns.is_empty() {
		return;
	}
	q.push_str("$texturegroup \"skinfamilies\"\n{\n");
	for row in &model.skins {
		let names: Vec<String> = columns
			.iter()
			.map(|&c| {
				let material = row.get(c).and_then(|&m| model.materials.get(m as usize));
				quote(material.map_or("", String::as_str))
			})
			.collect();
		let _ = writeln!(q, "\t{{ {} }}", names.join(" "));
	}
	q.push_str("}\n");
}

/// The inside of the stored `mdlkeyvalue` block, one pair per line.
fn key_values(text: &str) -> Option<String> {
	let root = vdf::parse(text, ParseOptions::RAW).ok()?;
	let block = root.find("mdlkeyvalue")?;
	if block.children().is_empty() {
		return None;
	}
	let mut out = String::new();
	for node in block.children() {
		write_node(&mut out, node, 1);
	}
	Some(out)
}

fn write_node(out: &mut String, node: &Node, depth: usize) {
	let indent = "\t".repeat(depth);
	match node.as_str() {
		Some(value) => {
			let _ = writeln!(out, "{indent}{} {}", quote(&node.key), quote(value));
		}
		None => {
			let _ = writeln!(out, "{indent}{}\n{indent}{{", quote(&node.key));
			for child in node.children() {
				write_node(out, child, depth + 1);
			}
			let _ = writeln!(out, "{indent}}}");
		}
	}
}

/// Pitch, yaw and roll in degrees, the inverse of the engine's AngleMatrix.
fn matrix_angles(m: [[f32; 4]; 3]) -> [f32; 3] {
	let forward = [m[0][0], m[1][0], m[2][0]];
	let left = [m[0][1], m[1][1], m[2][1]];
	let up_z = m[2][2];
	let xy = (forward[0] * forward[0] + forward[1] * forward[1]).sqrt();
	let (pitch, yaw, roll) = if xy > 0.001 {
		(
			(-forward[2]).atan2(xy),
			forward[1].atan2(forward[0]),
			left[2].atan2(up_z),
		)
	} else {
		((-forward[2]).atan2(xy), (-left[0]).atan2(left[1]), 0.0)
	};
	[pitch.to_degrees(), yaw.to_degrees(), roll.to_degrees()]
}

